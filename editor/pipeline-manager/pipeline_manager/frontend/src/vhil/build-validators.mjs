/*
 * vHIL (CHANGELOG-VHIL.md): Pipeline Manager's JSON-schema validators,
 * compiled once at build time into standalone code (Ajv's `standaloneCode`).
 * Upstream compiles them in the browser, and Ajv compiles through
 * `new Function`, which a `script-src 'self'` CSP refuses; the editor now
 * only runs the code written here. `npm run build-server-app` runs this
 * first (package.json), and so does `./build server-app`.
 *
 *   node src/vhil/build-validators.mjs      # -> src/vhil/validators/{editor,rpc}.js
 *
 * Each module exports `validators`: "<schema $id><reference>" -> validate
 * function, the key validate-json.js looks a schema up by. The two Ajv
 * configurations are upstream's: EditorManager.validateJSONWithSchema
 * (specification, dataflow, metadata, message schemas, and the node,
 * property and interface $defs the node editor checks) and
 * rpcCommunication.ts (each JSON-RPC endpoint's params and returns).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv2019 from 'ajv/dist/2019.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const resources = new URL('../../../resources/', import.meta.url);
const load = (path) => JSON.parse(readFileSync(new URL(path, resources), 'utf8'));
const out = new URL('./validators/', import.meta.url);

// Every key a validator is looked up by: the schema's own, and each of its $defs.
const keysOf = (schema) => [schema.$id, ...Object.keys(schema.$defs ?? {})
    .map((name) => `${schema.$id}#/$defs/${name}`)];

function write(name, ajv, keys) {
    // Export names must be identifiers; the lookup table maps the keys to them.
    const refs = Object.fromEntries(keys.map((key, i) => [`v${i}`, key]));
    // Ajv's ESM output still require()s its runtime helpers (e.g.
    // ajv/dist/runtime/equal), which an ES module under node has no
    // require for: import them instead. They are CommonJS with a `default`
    // export, which webpack and node expose differently, hence `cjs`.
    const imports = [];
    const code = standaloneCode(ajv, refs).replace(/require\("([^"]+)"\)\.default/g, (_, mod) => {
        imports.push(`import * as rt${imports.length} from ${JSON.stringify(`${mod}.js`)};`);
        return `cjs(rt${imports.length - 1})`;
    });
    if (/\brequire\(/.test(code)) throw new Error(`${name}: a require() left in the standalone code`);
    const table = keys.map((key, i) => `    ${JSON.stringify(key)}: v${i},`).join('\n');
    mkdirSync(out, { recursive: true });
    writeFileSync(new URL(`${name}.js`, out),
        `/* eslint-disable */\n// Generated by src/vhil/build-validators.mjs: do not edit.\n${imports.join('\n')}\n` +
        `const cjs = (m) => m.default?.default ?? m.default;\n${code}\n` +
        `export const validators = {\n${table}\n};\n`);
    // Its types, so TypeScript's checker reads these instead of inferring
    // them from the generated code (which overflows its stack).
    writeFileSync(new URL(`${name}.d.ts`, out),
        '// Generated by src/vhil/build-validators.mjs: do not edit.\n' +
        'export declare const validators: Record<string, ((data: unknown) => boolean)' +
        ' & { errors?: Array<Record<string, any>> | null }>;\n');
    console.log(`src/vhil/validators/${name}.js: ${keys.length} validators`);
}

// EditorManager.validateJSONWithSchema's Ajv, as upstream configures it.
const editorSchemas = ['unresolved_specification_schema', 'specification_schema',
    'metadata_schema', 'dataflow_schema', 'graph_schema']
    .map((name) => load(`schemas/${name}.json`));
const messageSchema = load('schemas/message_schema.json');
const editor = new Ajv2019({
    allowUnionTypes: true,
    addUsedSchema: false,
    formats: { hex: /^0x[a-fA-F0-9]+$/ },
    schemas: [...editorSchemas, messageSchema],
    code: { source: true, esm: true },
});
editor.addKeyword('version');
write('editor', editor, [...editorSchemas, messageSchema].flatMap(keysOf));

// rpcCommunication.ts's Ajv: each endpoint's params and returns, with the
// $id loadEndpoints gives them ("<method>_params", "<method>_returns").
const api = load('api_specification/specification.json');
const rpc = new Ajv2019({
    schemas: [load('api_specification/common_types.json')],
    allowUnionTypes: true,
    strict: true,
    code: { source: true, esm: true },
});
const rpcKeys = [];
for (const group of ['frontend_endpoints', 'backend_endpoints', 'external_endpoints']) {
    for (const [method, definition] of Object.entries(api[group])) {
        for (const part of ['params', 'returns']) {
            if (!definition[part]) continue;
            const id = `${method}_${part}`;
            if (rpc.getSchema(id)) continue;   // a method in two groups: one schema
            rpc.addSchema({ ...definition[part], $id: id });
            rpcKeys.push(id);
        }
    }
}
write('rpc', rpc, rpcKeys);
